"""Generate the Claude Code agent roster (.claude/agents/*.md, roster.json, docs/AGENT_ROSTER.md section) from goals/ [ADR-016].

One agent per committee role (goals/00..28), per build epic (goals/build/E01..E15), per gate (goals/gate_*) and one
for the Master Delivery Orchestrator (GOAL.md). The prompt text is copied verbatim from the goals file so the goals
directory stays the single source of truth; ``--check`` fails when the generated files drift from it.
"""

